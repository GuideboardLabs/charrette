"""Bundle the shared renderer into the desktop plugin.

The Electron loader takes ONE plain-ESM file and refuses every specifier
except `@hermes/plugin-sdk`, `react` and `react/jsx-runtime`, so the engine is
inlined verbatim with its `export` keywords stripped, followed by the pane.

Run: python3 scripts/bundle.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENGINE = ROOT / "renderer" / "charrette.mjs"
FONT = ROOT / "renderer" / "fonts" / "CharretteHand.woff2"
PANE = ROOT / "desktop" / "pane.js"
OUT = ROOT / "desktop" / "plugin.js"

HEADER = """/**
 * Charrette — desktop pane. GENERATED by scripts/bundle.py; edit the sources.
 *
 * Engine: renderer/charrette.mjs (the same file the web page imports).
 * Pane:   desktop/pane.js
 *
 * One white canvas beside the chat. The agent's marks arrive through the same
 * board document the web surface reads, so both mounts always agree.
 */

import { host } from '@hermes/plugin-sdk'
import { useEffect, useRef, useState } from 'react'
import { jsx, jsxs } from 'react/jsx-runtime'

"""


def strip_exports(src: str) -> str:
    """Inline the engine: every top-level export becomes a plain declaration."""
    out = []
    for line in src.splitlines(keepends=True):
        stripped = line.lstrip()
        if stripped.startswith("export "):
            indent = line[: len(line) - len(stripped)]
            line = indent + stripped[len("export "):]
        out.append(line)
    src = "".join(out)
    if "export " in src:
        leftovers = [line for line in src.splitlines() if line.strip().startswith("export ")]
        raise SystemExit(f"unstripped exports: {leftovers}")
    return src
    return src


def main() -> None:
    import base64

    engine = strip_exports(ENGINE.read_text(encoding="utf-8"))
    pane = PANE.read_text(encoding="utf-8")
    font = base64.b64encode(FONT.read_bytes()).decode("ascii")
    body = HEADER + f'const FONT_B64 = "{font}"\n\n' + engine + "\n\n" + pane
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
